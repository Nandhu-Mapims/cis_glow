function batchLetters() {
  const map = {};
  let letter = 'A';
  for (let i = 1; i <= 26; i += 1) {
    map[i] = letter;
    letter = String.fromCharCode(letter.charCodeAt(0) + 1);
  }
  return map;
}

function formatPeriodTime(fromTime, toTime) {
  const fmt = (t) => {
    if (!t || String(t) === '00:00:00') return '';
    const d = new Date(`1970-01-01T${String(t).slice(0, 8)}`);
    return Number.isNaN(d.getTime()) ? '' : d.toLocaleTimeString('en-US', { hour: 'numeric', minute: '2-digit', hour12: true }).toLowerCase();
  };
  const from = fmt(fromTime);
  const to = fmt(toTime);
  return from && to ? `${from} - ${to}` : from || to || '';
}

function formatLegacyGeneratedAt(d = new Date()) {
  const datePart = d.toLocaleString('en-GB', {
    day: '2-digit',
    month: 'short',
    year: 'numeric',
    hour: 'numeric',
    minute: '2-digit',
    hour12: true,
  }).replace(',', '');
  const timePart = d.toLocaleString('en-US', {
    hour: 'numeric',
    minute: '2-digit',
    hour12: true,
  }).toLowerCase();
  return `${datePart} at ${timePart}`;
}

async function loadBannerImageUrl() {
  const rows = await prisma.$queryRawUnsafe(
    'SELECT banner_image FROM basic_banner_tb WHERE del = 1 AND id = 1 LIMIT 1',
  );
  const image = rows[0]?.banner_image;
  return image ? `/legacy/img/global_images/${encodeURIComponent(image)}` : '';
}

